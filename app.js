function getLocalizedText(value, lang = currentLang) {
  if (value == null) return '';
  if (typeof value !== 'object') return String(value);

  const localized = value[lang] ?? value.ru ?? value.kz ?? value.en;
  return localized == null || typeof localized === 'object'
    ? ''
    : String(localized);
}

function setLang(lang) {
  if (currentLang === lang) return;
  currentLang = lang;
  
  // Update lang-btn active states
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });

  // Update the "more" button appearance if ZH or HI selected
  const moreBtn = document.getElementById('lang-more-btn');
  if (moreBtn) {
    const isExtended = (lang === 'zh' || lang === 'hi');
    moreBtn.classList.toggle('open', isExtended);
  }

  // Translate all static texts
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (I18N[key] && I18N[key][lang]) {
      el.innerHTML = I18N[key][lang];
    }
  });

  // Translate placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (I18N[key] && I18N[key][lang]) {
      el.placeholder = I18N[key][lang];
    }
  });

  // Re-render everything with new language
  renderSuperCategories();
  renderCategories();
  renderGrid();
  renderHome();
  renderCabins();
  updateCartBar();
  renderPromos();
  renderStatusBadge();
  updateTrustSection();
  if (modalId) {
    // Refresh modal text
    const m = MENU.find(x => x.id === modalId);
    if (m) {
      document.getElementById('modal-name').textContent = m.name[currentLang];
      document.getElementById('modal-desc').textContent = m.desc[currentLang];
    }
  }
  if (document.getElementById('cart-drawer').classList.contains('open')) {
    renderDrawerItems();
  }
}

// ── LANG DROPDOWN HELPERS ─────────────────────────────────────
function toggleLangMore(e) {
  e.stopPropagation();
  const dropdown = document.getElementById('lang-dropdown');
  const btn      = document.getElementById('lang-more-btn');
  const isOpen   = dropdown.classList.toggle('open');
  btn.classList.toggle('open', isOpen);

  if (isOpen) {
    // Close on outside click
    const close = (ev) => {
      if (!document.getElementById('lang-more-wrap').contains(ev.target)) {
        closeLangMore();
      }
      document.removeEventListener('click', close);
    };
    setTimeout(() => document.addEventListener('click', close), 0);
  }
}

