let content = fs.readFileSync('app.js', 'utf8');
let menuStart = content.indexOf('const MENU = [');
let menuEnd = content.indexOf('];', menuStart);
let menuStr = content.substring(menuStart + 'const MENU = '.length, menuEnd + 1);

let MENU;
eval('MENU = ' + menuStr);

let newItems = [];
for (let item of MENU) {
  if (item.desc) {
    if (mapRu[item.id]) {
      item.desc.ru = mapRu[item.id];
      item.desc.kz = mapRu[item.id]; // fallback
      item.desc.en = mapRu[item.id]; // fallback
    }
  }
  
  let str = `  { id:${item.id}, cat:'${item.cat}', name: { ru: '${item.name.ru.replace(/'/g,"\\'")}', kz: '${item.name.kz.replace(/'/g,"\\'")}', en: '${item.name.en.replace(/'/g,"\\'")}', zh: '${item.name.zh ? item.name.zh.replace(/'/g,"\\'") : ''}' }`;
  if (item.weight) {
    str += `, weight:'${item.weight}'`;
  }
  if (item.desc) {
    str += `, desc: { ru: '${item.desc.ru.replace(/'/g,"\\'")}', kz: '${item.desc.kz.replace(/'/g,"\\'")}', en: '${item.desc.en.replace(/'/g,"\\'")}', zh: '${item.desc.zh ? item.desc.zh.replace(/'/g,"\\'") : ''}' }`;
  }
  str += `, price:${item.price}, origPrice:${item.origPrice}, img:'${item.img}', emoji:'${item.emoji}', gradient:['${item.gradient[0]}','${item.gradient[1]}'], rating:${item.rating}, reviews:${item.reviews} }`;
  
  newItems.push(str);
}

let newMenuBlock = 'const MENU = [\n' + newItems.join(',\n') + '\n];';
let newContent = content.substring(0, menuStart) + newMenuBlock + content.substring(menuEnd + 2);
fs.writeFileSync('app.js', newContent);
console.log("Done patching descriptions!");
